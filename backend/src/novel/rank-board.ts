/** 给 prompt 用的榜单文本（太长会挤掉模型注意力，只给标题行 + 信号） */
export function renderRankBoard(platform?: string): string {
  const b = RANK_BOARD.boards.filter((x) => !platform || x.platform === platform || platform === '全部');
  const lines: string[] = [];
  b.forEach((x) => {
    lines.push(`【${x.platform}·${x.channel}·${x.board}】`);
    x.groups.forEach((g) => {
      lines.push(`  ${g.name}：` + g.items.slice(0, 10).join(' / '));
    });
  });
  return lines.join('\n');
}
